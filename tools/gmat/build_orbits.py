#!/usr/bin/env python3
"""Runs GMAT once per orbit and writes eclipse_fraction, reference_duration_s and
contacts_s into data/orbits.json.

usage: tools/gmat/build_orbits.py /path/to/GMAT/R2025a/bin

Every orbit in orbits.json names a gmat_case; the cases live in CASES below and
are documented in RESEARCH.md. The generated GMAT scripts land in
tools/gmat/cases/ so a run can be repeated by hand.
"""
import json
import math
import subprocess
import sys
import tempfile
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASES_DIR = Path(__file__).resolve().parent / "cases"
R_EARTH_KM = 6378.137
EPOCH_FMT = "%d %b %Y %H:%M:%S.%f"

# epoch is northern fire season. ltan_h pins the RAAN for sun-synchronous cases,
# raan_deg is used as is when there is no ltan (the ISS orbit drifts anyway).
CASES = {
    "leo_400_2027_07": {"epoch": "01 Jul 2027 00:00:00.000", "days": 7, "raan_deg": 0.0},
    "sso_550_2027_07": {"epoch": "01 Jul 2027 00:00:00.000", "days": 7, "ltan_h": 10.5},
    "sso_700_2027_07": {"epoch": "01 Jul 2027 00:00:00.000", "days": 7, "ltan_h": 10.5},
}


def sun_right_ascension_deg(when: datetime) -> float:
    # low precision solar position, good to ~0.01 deg (Astronomical Almanac, C5)
    n = (when - datetime(2000, 1, 1, 12)).total_seconds() / 86400.0
    L = math.radians((280.460 + 0.9856474 * n) % 360.0)
    g = math.radians((357.528 + 0.9856003 * n) % 360.0)
    lam = L + math.radians(1.915) * math.sin(g) + math.radians(0.020) * math.sin(2 * g)
    eps = math.radians(23.439 - 0.0000004 * n)
    return math.degrees(math.atan2(math.cos(eps) * math.sin(lam), math.cos(lam))) % 360.0


def raan_for(case: dict, epoch: datetime) -> float:
    if "ltan_h" not in case:
        return case["raan_deg"]
    # ascending node sits (ltan - 12 h) of hour angle away from the Sun
    return (sun_right_ascension_deg(epoch) + (case["ltan_h"] - 12.0) * 15.0) % 360.0


def gmat_name(station_id: str) -> str:
    return "GS_" + "".join(ch for ch in station_id if ch.isalnum())


def write_script(orbit: dict, stations: list, case: dict, out_dir: Path) -> str:
    epoch = datetime.strptime(case["epoch"], EPOCH_FMT)
    lines = [
        f"% generated by tools/gmat/build_orbits.py for {orbit['id']}",
        "Create Spacecraft Sat;",
        "GMAT Sat.DateFormat = UTCGregorian;",
        f"GMAT Sat.Epoch = '{case['epoch']}';",
        "GMAT Sat.CoordinateSystem = EarthMJ2000Eq;",
        "GMAT Sat.DisplayStateType = Keplerian;",
        f"GMAT Sat.SMA = {R_EARTH_KM + orbit['altitude_km']:.3f};",
        "GMAT Sat.ECC = 0;",
        f"GMAT Sat.INC = {orbit['inclination_deg']};",
        f"GMAT Sat.RAAN = {raan_for(case, epoch):.4f};",
        "GMAT Sat.AOP = 0;",
        "GMAT Sat.TA = 0;",
    ]
    for s in stations:
        n = gmat_name(s["id"])
        lines += [
            f"Create GroundStation {n};",
            f"GMAT {n}.CentralBody = Earth;",
            f"GMAT {n}.StateType = Spherical;",
            f"GMAT {n}.HorizonReference = Ellipsoid;",
            f"GMAT {n}.Location1 = {s['latitude_deg']};",
            f"GMAT {n}.Location2 = {s['longitude_deg'] % 360.0};",
            f"GMAT {n}.Location3 = {s['altitude_km']};",
            f"GMAT {n}.MinimumElevationAngle = {s['min_elevation_deg']};",
        ]
    observers = ", ".join(gmat_name(s["id"]) for s in stations)
    lines += [
        "Create ForceModel FM;",
        "GMAT FM.CentralBody = Earth;",
        "GMAT FM.PrimaryBodies = {Earth};",
        "GMAT FM.GravityField.Earth.Degree = 4;",
        "GMAT FM.GravityField.Earth.Order = 4;",
        "GMAT FM.GravityField.Earth.PotentialFile = 'JGM3.cof';",
        "Create Propagator Prop;",
        "GMAT Prop.FM = FM;",
        "GMAT Prop.Type = RungeKutta89;",
        "GMAT Prop.MaxStep = 60;",
        "Create ContactLocator CL;",
        "GMAT CL.Target = Sat;",
        f"GMAT CL.Filename = '{out_dir / 'contacts.txt'}';",
        f"GMAT CL.Observers = {{{observers}}};",
        "GMAT CL.StepSize = 10;",
        "GMAT CL.UseLightTimeDelay = false;",
        "GMAT CL.UseStellarAberration = false;",
        "GMAT CL.WriteReport = true;",
        "GMAT CL.RunMode = Automatic;",
        "GMAT CL.UseEntireInterval = true;",
        "Create EclipseLocator EL;",
        "GMAT EL.Spacecraft = Sat;",
        f"GMAT EL.Filename = '{out_dir / 'eclipses.txt'}';",
        "GMAT EL.OccultingBodies = {Earth};",
        "GMAT EL.EclipseTypes = {'Umbra', 'Penumbra'};",
        "GMAT EL.StepSize = 10;",
        "GMAT EL.UseLightTimeDelay = false;",
        "GMAT EL.UseStellarAberration = false;",
        "GMAT EL.WriteReport = true;",
        "GMAT EL.RunMode = Automatic;",
        "GMAT EL.UseEntireInterval = true;",
        "BeginMissionSequence;",
        f"Propagate Prop(Sat) {{Sat.ElapsedDays = {case['days']}}};",
    ]
    return "\n".join(lines) + "\n"


def parse_rows(text: str):
    """Yields (section_name, start, stop) for every interval row in a locator report."""
    section = None
    for line in text.splitlines():
        if line.startswith("Observer:"):
            section = line.split(":", 1)[1].strip()
            continue
        parts = line.split()
        if len(parts) < 8:
            continue
        try:
            start = datetime.strptime(" ".join(parts[0:4]), EPOCH_FMT)
            stop = datetime.strptime(" ".join(parts[4:8]), EPOCH_FMT)
        except ValueError:
            continue
        yield section, start, stop


def run_case(gmat_bin: Path, orbit: dict, stations: list) -> dict:
    case = CASES[orbit["gmat_case"]]
    epoch = datetime.strptime(case["epoch"], EPOCH_FMT)
    window_s = case["days"] * 86400.0
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        script = write_script(orbit, stations, case, tmp_path)
        CASES_DIR.mkdir(exist_ok=True)
        # the committed copy points its reports at GMAT's own output folder
        (CASES_DIR / f"{orbit['gmat_case']}.script").write_text(script.replace(str(tmp_path) + "/", ""))
        script_path = tmp_path / "case.script"
        script_path.write_text(script)
        subprocess.run(["./GmatConsole", "--run", str(script_path)], cwd=gmat_bin, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        contacts_txt = (tmp_path / "contacts.txt").read_text()
        eclipses_txt = (tmp_path / "eclipses.txt").read_text()

    by_name = {gmat_name(s["id"]): s["id"] for s in stations}
    contacts = {s["id"]: [] for s in stations}
    for section, start, stop in parse_rows(contacts_txt):
        rel = [round((start - epoch).total_seconds(), 1), round((stop - epoch).total_seconds(), 1)]
        contacts[by_name[section]].append(rel)
    dark_s = sum((stop - start).total_seconds() for _, start, stop in parse_rows(eclipses_txt))
    return {
        "eclipse_fraction": round(dark_s / window_s, 4),
        "reference_duration_s": window_s,
        "contacts_s": {k: sorted(v) for k, v in contacts.items()},
    }


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    gmat_bin = Path(sys.argv[1]).expanduser().resolve()
    orbits_path = ROOT / "data" / "orbits.json"
    orbits = json.loads(orbits_path.read_text())
    stations = json.loads((ROOT / "data" / "ground_stations.json").read_text())
    for orbit in orbits:
        result = run_case(gmat_bin, orbit, stations)
        orbit.update(result)
        per_day = sum(e - s for w in result["contacts_s"].values() for s, e in w) / (result["reference_duration_s"] / 86400.0)
        print(f"{orbit['id']}: eclipse {result['eclipse_fraction']:.3f}, contact {per_day:.0f} s/day over all stations")
    # contact lists stay on one line per station, the file would be thousands of lines otherwise
    text = json.dumps(orbits, indent=2)
    orbits_path.write_text(_compact_pairs(text) + "\n")


def _compact_pairs(text: str) -> str:
    import re
    text = re.sub(r"\[\s+([-\d.]+),\s+([-\d.]+)\s+\]", r"[\1, \2]", text)
    return re.sub(r"\[\s+(\[[^\n]*\])((?:,\s+\[[^\n]*\])*)\s+\]",
                  lambda m: "[" + re.sub(r",\s+", ", ", m.group(1) + m.group(2)) + "]", text)


if __name__ == "__main__":
    main()
